export function anonName(userId: string): string {
  let hash = 0;
  for (let i = 0; i < userId.length; i++) {
    hash = (hash * 31 + userId.charCodeAt(i)) | 0;
  }
  return ANON_NAMES[Math.abs(hash) % ANON_NAMES.length];
}
